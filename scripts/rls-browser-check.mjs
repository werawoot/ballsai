// Writes docs/security/rls-browser-check.js: the T21 checks of scripts/rls-minor-checks.mjs that
// need no test ids but the athlete's (the signed-out sweep, the birth-date checks and every
// training-data check), as one script to paste into the browser console on the Staging site,
// signed in as the person whose access is being tested. The id-based checks on profiles, links,
// teams, payments, draws and organizations stay with the terminal runner (rls-smoke-test.mjs). It uses that browser's own session
// token, never prints or sends it anywhere but Staging's API, and writes nothing on purpose. The owner can run it
// through Claude in Chrome without a terminal and without anyone handling a JWT (T21).
// Run: node scripts/rls-browser-check.mjs
import { readFileSync, writeFileSync, mkdirSync } from 'node:fs'
import { pathToFileURL } from 'node:url'
import { SIGNED_OUT_CLOSED_TABLES, TRAINING_TABLES } from './rls-minor-checks.mjs'

// Staging only: the API address is fixed to this project, and the run stops if ANON_KEY is not
// Staging's.
export const STAGING_REF = 'vorpnkedpscsqhnrssrl'

// The check list's own source text, taken from the file (not Function.toString(), which a
// bundler or test runner may rewrite), so the browser runs exactly the checks the Node runner does.
function checkBuilderSource() {
  const text = readFileSync(new URL('./rls-minor-checks.mjs', import.meta.url), 'utf8')
  const start = text.indexOf('export function buildMinorDataChecks(ids) {')
  const end = text.indexOf('\n}\n', start)
  if (start < 0 || end < 0) throw new Error('buildMinorDataChecks not found in rls-minor-checks.mjs')
  return text.slice(start + 'export '.length, end + 2).split('\n').map((line, index) => index === 0 ? line : `  ${line}`).join('\n')
}

export function browserCheckSource() {
  return `// DOENSAI RLS check in the browser (T21), generated by scripts/rls-browser-check.mjs. Do not edit.
// Staging only: it calls https://${STAGING_REF}.supabase.co and nothing else. It reads, and tries
// writes that must be refused (shaped to store nothing where possible). It uses this browser's own
// sign-in, never prints the token, and reports PASS / FAIL / SKIP for each check.
// Set the three values below, paste the whole script into the console of the Staging site.
(async () => {
  const ROLE = 'anonymous' // 'anonymous' (signed out) | 'owner' (the test athlete) | 'guardian' | 'unrelated' | 'admin'
  const ATHLETE_ID = ''    // for 'guardian', 'unrelated' and 'admin': the athlete id printed by the 'owner' run
  const ANON_KEY = ''      // Staging's public anon (publishable) key: Supabase > Project Settings > API

  const REF = '${STAGING_REF}'
  const API = 'https://' + REF + '.supabase.co/rest/v1'
  const SIGNED_OUT_CLOSED_TABLES = ${JSON.stringify(SIGNED_OUT_CLOSED_TABLES)}
  const TRAINING_TABLES = ${JSON.stringify(TRAINING_TABLES)}
  ${checkBuilderSource()}

  if (!ANON_KEY) { console.error('Set ANON_KEY first.'); return }
  if (!['anonymous', 'owner', 'guardian', 'unrelated', 'admin'].includes(ROLE)) { console.error('ROLE must be anonymous, owner, guardian, unrelated or admin.'); return }
  if (['unrelated', 'admin'].includes(ROLE) && !ATHLETE_ID) { console.error('Set ATHLETE_ID (printed by the owner run) for this role.'); return }

  // The browser's Supabase session: cookie sb-<ref>-auth-token, possibly split into .0, .1, ...
  function sessionToken() {
    const jar = Object.fromEntries(document.cookie.split('; ').filter(Boolean).map(part => {
      const at = part.indexOf('=')
      let value = part.slice(at + 1)
      try { value = decodeURIComponent(value) } catch {}
      return [part.slice(0, at), value]
    }))
    const name = 'sb-' + REF + '-auth-token'
    let raw = jar[name] ?? ''
    for (let index = 0; !jar[name] && jar[name + '.' + index] !== undefined; index++) raw += jar[name + '.' + index]
    if (!raw) return null
    if (raw.startsWith('base64-')) raw = atob(raw.slice(7).replace(/-/g, '+').replace(/_/g, '/'))
    try { return JSON.parse(raw).access_token ?? null } catch { return null }
  }
  const subject = jwt => { try { return JSON.parse(atob(jwt.split('.')[1].replace(/-/g, '+').replace(/_/g, '/'))).sub } catch { return null } }

  const token = ROLE === 'anonymous' ? '' : sessionToken()
  if (ROLE !== 'anonymous' && !token) { console.error('No Staging sign-in found in this browser. Sign in on the Staging site, then run again.'); return }
  const me = token ? subject(token) : null
  const call = async (path, options = {}) => {
    const response = await fetch(API + path, { ...options, headers: { apikey: ANON_KEY, 'content-type': 'application/json', prefer: 'return=minimal', ...(token ? { authorization: 'Bearer ' + token } : {}) } })
    const text = await response.text()
    let body = text
    try { body = text ? JSON.parse(text) : null } catch {}
    return { status: response.status, body }
  }

  // A key from another project gets 401 on everything, which would make every "refused" check
  // pass. Stop unless the key is Staging's.
  const probe = await call('/athlete_profiles?select=user_id&limit=1')
  if (probe.status === 401) { console.error('ANON_KEY is not the Staging key (the API refused it). Copy the anon key of project ' + REF + '.'); return }

  // The test athlete: the owner is the signed-in athlete; the others name it with ATHLETE_ID.
  const results = []
  let athlete = ROLE === 'owner' ? me : ATHLETE_ID
  if (ROLE === 'guardian') {
    const link = await call('/guardian_links?select=athlete_id&status=eq.accepted&guardian_id=eq.' + me + (ATHLETE_ID ? '&athlete_id=eq.' + ATHLETE_ID : '') + '&limit=1')
    athlete = Array.isArray(link.body) && link.body[0] ? link.body[0].athlete_id : ''
    if (!athlete) results.push({ outcome: 'FAIL', check: 'this guardian has an accepted link to the test athlete (sign in as the guardian of that athlete)', http: link.status, rows: 0 })
  }
  if (ROLE !== 'owner' && ROLE !== 'anonymous' && athlete === me) { console.error('Sign in as a different person than the test athlete.'); return }
  const ids = athlete ? { TRAINING_ATHLETE_ID: athlete } : {}

  for (const check of buildMinorDataChecks(ids).filter(item => item.audience === ROLE)) {
    const result = await call(check.path, check.method === 'POST' ? { method: 'POST', body: JSON.stringify(check.body) } : {})
    const rows = Array.isArray(result.body) ? result.body.length : null
    let outcome
    if (result.status === 404 && /PGRST20[25]/.test(JSON.stringify(result.body ?? ''))) outcome = 'SKIP'
    else if (check.expected === 'visible') outcome = result.status === 200 && rows > 0 ? 'PASS' : 'FAIL'
    else if (check.expected === 'hidden') outcome = result.status === 200 && rows === 0 ? 'PASS' : 'FAIL'
    else if (check.expected === 'denied') outcome = [401, 403].includes(result.status) ? 'PASS' : 'FAIL'
    else outcome = [401, 403, 404].includes(result.status) || (result.status === 200 && rows === 0) ? 'PASS' : 'FAIL'
    results.push({ outcome, check: check.label, http: result.status, rows })
  }
  console.table(results)
  const count = outcome => results.filter(item => item.outcome === outcome).length
  console.log('ROLE ' + ROLE + ': PASS ' + count('PASS') + ', FAIL ' + count('FAIL') + ', SKIP ' + count('SKIP') + ' of ' + results.length)
  if (ROLE === 'owner') console.log('ATHLETE_ID for the unrelated run: ' + me)
})()
`
}

if (process.argv[1] && import.meta.url === pathToFileURL(process.argv[1]).href) {
  mkdirSync(new URL('../docs/security/', import.meta.url), { recursive: true })
  writeFileSync(new URL('../docs/security/rls-browser-check.js', import.meta.url), browserCheckSource())
  console.log('wrote docs/security/rls-browser-check.js')
}
